// Finds, for every job, the number of items that takes the simulated
// ordinary worker exactly one workday (8h, breaks not included).
// Run: node tools/calibrate.mjs          -> writes src/calibration.js
//      node tools/calibrate.mjs --check  -> fails if src/calibration.js is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { JOBS, WORKDAY, buildLayout } from '../src/jobs.js';
import { simulate, fmtDuration } from '../src/sim.js';

const out = {};
for (const job of JOBS) {
  const run = (n) => simulate(job, buildLayout(job, n), null, { record: false });
  let lo = 10, hi = 20;
  while (run(hi).total < WORKDAY) { lo = hi; hi *= 2; }
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (run(mid).total < WORKDAY) lo = mid; else hi = mid;
  }
  // Pick whichever count lands closer to 8:00:00.
  const a = run(lo), b = run(hi);
  const n = Math.abs(a.total - WORKDAY) <= Math.abs(b.total - WORKDAY) ? lo : hi;
  const r = n === lo ? a : b;
  const first = r.trips.slice(0, 20), lastT = r.trips.slice(-20);
  const avg = (ts) => ts.reduce((s, t) => s + (t.t1 - t.t0), 0) / ts.length;
  out[job.id] = {
    count: n,
    total: Math.round(r.total),
    trips: r.trips.length,
    walkedKm: +(r.walked / 1000).toFixed(2),
  };
  console.log(
    `${job.title.padEnd(10)} ${String(n).padStart(6)} ${job.item[1].padEnd(7)} ` +
    `${fmtDuration(r.total)}  ${r.trips.length} trips  ${(r.walked / 1000).toFixed(1)} km walked  ` +
    `first trips ~${avg(first).toFixed(0)}s, last trips ~${avg(lastT).toFixed(0)}s`
  );
}
const file = new URL('../src/calibration.js', import.meta.url);
const text = '// Generated by tools/calibrate.mjs - do not edit by hand.\n' +
  `export const CALIBRATION = ${JSON.stringify(out, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== text) {
    console.error('src/calibration.js is out of date. Run: npm run calibrate');
    process.exit(1);
  }
  console.log('calibration up to date');
} else writeFileSync(file, text);
